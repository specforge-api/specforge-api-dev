//! Auto-generates TypeScript / Jest & Vitest contract test suites.

use specforge_fuzzer::invariants::TestCase;

pub struct JestExporter;

impl JestExporter {
    pub fn export(test_cases: &[TestCase], target_url: &str) -> String {
        let mut out = String::new();
        out.push_str("/**\n");
        out.push_str(" * Auto-generated by SpecForge Dev (Rust Engine)\n");
        out.push_str(" * Target: Node.js / Express.js Contract Boundary Suite\n");
        out.push_str(" */\n\n");
        out.push_str("import request from 'supertest';\n\n");
        out.push_str(&format!("const BASE_URL = process.env.API_BASE_URL || '{}';\n\n", target_url));
        out.push_str("describe('SpecForge API Contract & Boundary Test Suite', () => {\n");

        for tc in test_cases {
            let escaped_name = tc.mutation_name.replace('\'', "\\'");
            let escaped_field = tc.field_name.replace('\'', "\\'");
            let method = tc.method.to_lowercase();

            out.push_str(&format!(
                "  it('{} {} [Field: {}] - {}', async () => {{\n",
                tc.method.to_uppercase(),
                tc.endpoint,
                escaped_field,
                escaped_name
            ));

            out.push_str(&format!("    const req = request(BASE_URL).{}(\"{}\");\n", method, tc.endpoint));

            if let Some(ref payload) = tc.payload {
                let json_str = serde_json::to_string(payload).unwrap_or_else(|_| "{}".to_string());
                out.push_str(&format!("    const res = await req.send({});\n", json_str));
            } else {
                out.push_str("    const res = await req;\n");
            }

            out.push_str("    // INVARIANT 1: Zero 500s (Server must never crash)\n");
            out.push_str("    expect(res.status).toBeLessThan(500);\n");

            if tc.is_negative_test {
                out.push_str("    // INVARIANT 2: Reject malformed inputs with clean 400 or 422\n");
                out.push_str("    expect([400, 422]).toContain(res.status);\n");
            } else {
                out.push_str("    // INVARIANT 3: Baseline valid request must succeed\n");
                out.push_str("    expect(res.status).toBeGreaterThanOrEqual(200);\n");
                out.push_str("    expect(res.status).toBeLessThan(300);\n");
            }

            out.push_str("  });\n\n");
        }

        out.push_str("});\n");
        out
    }
}

