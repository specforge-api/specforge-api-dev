//! Auto-generates Python / Pytest contract test suites with @pytest.mark.parametrize.

use specforge_fuzzer::invariants::TestCase;

pub struct PytestExporter;

impl PytestExporter {
    pub fn export(test_cases: &[TestCase], target_url: &str) -> String {
        let mut out = String::new();
        out.push_str("\"\"\"\n");
        out.push_str("Auto-generated by SpecForge Dev (Rust Engine)\n");
        out.push_str("Target: Python / FastAPI & Flask Contract Boundary Suite\n");
        out.push_str("\"\"\"\n\n");
        out.push_str("import pytest\n");
        out.push_str("import httpx\n\n");
        out.push_str(&format!("BASE_URL = \"{}\"\n\n", target_url));

        for tc in test_cases {
            let func_name = format!(
                "test_{}_{}_{}",
                tc.method.to_lowercase(),
                tc.endpoint.trim_matches('/').replace(['/', '-', '{', '}'], "_"),
                tc.id
            );

            let desc = tc.description.replace('"', "\\\"");

            out.push_str(&format!("def {}():\n", func_name));
            out.push_str(&format!("    \"\"\"{}\"\"\"\n", desc));
            out.push_str("    with httpx.Client(base_url=BASE_URL, timeout=10.0) as client:\n");

            let method = tc.method.to_uppercase();
            if let Some(ref payload) = tc.payload {
                let json_str = serde_json::to_string(payload).unwrap_or_else(|_| "{}".to_string());
                out.push_str(&format!(
                    "        response = client.request(\"{}\", \"{}\", json={})\n",
                    method, tc.endpoint, json_str
                ));
            } else {
                out.push_str(&format!(
                    "        response = client.request(\"{}\", \"{}\")\n",
                    method, tc.endpoint
                ));
            }

            out.push_str("        # INVARIANT 1: Zero 500s (Server must never crash)\n");
            out.push_str(&format!(
                "        assert response.status_code != 500, f\"Server crashed on: {}\"\n",
                desc
            ));

            if tc.is_negative_test {
                out.push_str("        # INVARIANT 2: Reject malformed inputs with clean 400 or 422\n");
                out.push_str("        assert response.status_code in (400, 422), f\"Expected 400 or 422, got {response.status_code}\"\n\n");
            } else {
                out.push_str("        # INVARIANT 3: Baseline valid request must succeed\n");
                out.push_str("        assert 200 <= response.status_code < 300, f\"Expected 2xx status, got {response.status_code}\"\n\n");
            }
        }

        out
    }
}

